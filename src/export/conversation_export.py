"""Export Claude Code conversation history into second-brain staging format.

Parses JSONL session files from ~/.claude/projects/ and produces
structured conversation batches for extraction and loading.

Who said what comes from the fields Claude Code writes on each record, not from
the message role. The user role carries what the owner typed, and also skill and
command bodies, compaction summaries, task notifications, command output and the
messages of other sessions and agents. Only what the owner typed is speaker
'user'; the rest of the user role is speaker 'agent'. A session an agent ran (a
teammate or a subagent, whose records name it) holds no owner turn, and a
session with no owner turn is kind 'agent': left out of the export unless asked
for, and out of every conversation read path by default. The kind is not stored
on its own: a stored conversation is an agent session when it holds user-role
turns and none of them is the owner's (src/store/conversation_query.py).

Staging holds one file per session and version, and the export reads a transcript
again only when it changed (export_conversations).
"""

import hashlib
import json
import re
from datetime import datetime
from pathlib import Path

from src.config import CLAUDE_CODE_PROJECTS_DIR, CONVERSATION_STAGING_DIR
from src.export.state import load_json_or_quarantine, write_json_atomic

# Staged copies: one file per session and version, conversation-session-<id>.<end>.<turns>.json
# (staged_path), and the batches of several sessions written before those, named
# conversation-batch-<time>.json, until a load splits them (src/store/loader.py). A later
# copy of a session wins: the batches sort before the session files, and the files of one
# session sort by version.
STAGED_GLOB = "conversation-*.json"

# What the export learnt from each transcript it read, kept beside the staged copies and
# never matched by STAGED_GLOB (export_conversations).
TRANSCRIPTS_READ = "transcripts-read.json"

# Record types that carry conversation content
_CONTENT_TYPES = {"user", "assistant"}

# Record types to skip entirely
_SKIP_TYPES = {"file-history-snapshot", "last-prompt", "progress", "queue-operation"}

# Minimum turns the assistant did not write for a conversation to be worth exporting
MIN_USER_TURNS = 2

# Speakers. 'user' is the owner and nobody else.
OWNER = "user"
AGENT = "agent"
ASSISTANT = "assistant"

# promptSource on a record the owner typed: at the prompt, queued while a turn
# ran, or a suggestion he accepted. 'sdk' and 'system' are not his.
OWNER_PROMPT_SOURCES = frozenset({"typed", "queued", "suggestion_accepted"})

# How the user-role text the owner did not type opens. Claude Code marks most of
# it (isMeta, isCompactSummary, origin, promptSource), but a message from another
# session, a slash command's echo and output, an interrupted request and a
# teammate's message carry none of those fields, and a transcript older than
# 2.1.259 carries none at all.
HARNESS_OPENINGS = (
    "<teammate-message",
    "<task-notification",
    "<system-reminder",
    "<cross-session-message",
    "<command-name",
    "<command-message",
    "<command-args",
    "<local-command-",
    "<bash-input",
    "<bash-stdout",
    "<bash-stderr",
    "Another Claude session sent a message",
    "Base directory for this skill",
    "This session is being continued from a previous conversation",
    "Caveat: The messages below were generated by the user while running local commands",
    "[Request interrupted by user",
)

# A record names the agent whose session it is: a teammate's name and team, a
# subagent's id. Read off user and assistant records only: a session's title is a
# record of its own type keyed agentName, and an owner's session holds agent ids
# inside its tool results.
_AGENT_FIELDS = ("agentName", "teamName", "agentId")

# Maximum content length per turn (truncate very long tool outputs)
MAX_TURN_CONTENT = 50_000


def _workspace_from_dir_name(dir_name: str) -> str:
    """Convert project directory name back to a readable path.

    e.g. '-Users-you-Downloads' → '/Users/you/Downloads'
    """
    return "/" + dir_name.lstrip("-").replace("-", "/")


def _project_name_from_workspace(workspace: str) -> str:
    """Extract a short project name from a workspace path.

    e.g. '/Users/you/SourceCode/plessas-second-brain' → 'plessas-second-brain'
    """
    parts = workspace.rstrip("/").split("/")
    return parts[-1] if parts else workspace


def _extract_text_content(message: dict) -> str:
    """Extract readable text from a message's content field.

    Handles both string content (user messages) and list content
    (assistant messages with text/thinking/tool_use blocks).
    """
    content = message.get("content", "")

    if isinstance(content, str):
        return content.strip()

    if isinstance(content, list):
        parts = []
        for block in content:
            block_type = block.get("type", "")
            if block_type == "text":
                text = block.get("text", "").strip()
                if text:
                    parts.append(text)
            elif block_type == "thinking":
                # Skip thinking blocks — internal reasoning
                pass
            elif block_type == "tool_use":
                tool_name = block.get("name", "unknown")
                tool_input = block.get("input", {})
                # Summarize tool use compactly
                if tool_name in ("Read", "Glob", "Grep"):
                    target = (
                        tool_input.get("file_path")
                        or tool_input.get("pattern")
                        or tool_input.get("path", "")
                    )
                    parts.append(f"[Tool: {tool_name} {target}]")
                elif tool_name == "Edit":
                    parts.append(f"[Tool: Edit {tool_input.get('file_path', '')}]")
                elif tool_name == "Write":
                    parts.append(f"[Tool: Write {tool_input.get('file_path', '')}]")
                elif tool_name == "Bash":
                    cmd = tool_input.get("command", "")[:100]
                    parts.append(f"[Tool: Bash {cmd}]")
                else:
                    parts.append(f"[Tool: {tool_name}]")
            elif block_type == "tool_result":
                # Tool results appear in user messages — skip them
                pass
        return "\n".join(parts)

    return str(content)[:MAX_TURN_CONTENT]


def _has_code_blocks(text: str) -> bool:
    """Check if text contains markdown code blocks."""
    return "```" in text


def is_agent_record(record: dict) -> bool:
    """Whether a record says an agent ran its session (a teammate or a subagent)."""
    return record.get("type") in _CONTENT_TYPES and any(record.get(f) for f in _AGENT_FIELDS)


def is_owner_record(record: dict, text: str) -> bool:
    """Whether the owner typed this user-role record, whose text is `text`.

    Not when Claude Code says it wrote it (isMeta, a skill or command body;
    isCompactSummary), when its origin is not a human or its promptSource not
    the owner's, when it opens like the harness's own text, or, on a record from
    before origin and promptSource, when it came through the SDK. Otherwise it is
    his, as every user record of a transcript older than those fields is.
    """
    if record.get("isMeta") or record.get("isCompactSummary"):
        return False
    origin = record.get("origin")
    kind = origin.get("kind") if isinstance(origin, dict) else origin
    source = record.get("promptSource")
    if kind is None and source is None:
        if str(record.get("entrypoint") or "").startswith("sdk"):
            return False
    elif (kind is not None and kind != "human") or (
        source is not None and source not in OWNER_PROMPT_SOURCES
    ):
        return False
    return not text.lstrip().startswith(HARNESS_OPENINGS)


def read_records(jsonl_path: Path) -> list[dict] | None:
    """The records of a transcript, skipping lines that are not JSON; None when unreadable."""
    records = []
    try:
        with open(jsonl_path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    records.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
    except (OSError, UnicodeDecodeError):
        return None
    return records


def legacy_turns(records: list[dict]) -> list[tuple[str, str, bool]]:
    """The turns the exporter made of `records` before it read provenance, as
    (speaker, content, whether the owner typed any record in it).

    It collapsed consecutive records by role alone, so a stored user turn can hold
    the owner's words and a skill body together. relabel-conversations lines these
    up with what the store holds (src/export/conversation_relabel.py).
    """
    agent_session = any(is_agent_record(r) for r in records)
    turns: list[tuple[str, str, bool]] = []
    for record in records:
        rec_type = record.get("type", "")
        if rec_type not in _CONTENT_TYPES:
            continue
        message = record.get("message", {})
        text = _extract_text_content(message)
        if not text:
            continue
        speaker = OWNER if message.get("role", rec_type) == "user" else ASSISTANT
        typed = speaker == OWNER and not agent_session and is_owner_record(record, text)
        if turns and turns[-1][0] == speaker:
            _, content, any_typed = turns[-1]
            turns[-1] = (speaker, f"{content}\n{text}", any_typed or typed)
        else:
            turns.append((speaker, text, typed))
    return turns


def parse_conversation(jsonl_path: Path) -> dict | None:
    """Parse a single JSONL conversation file into structured format.

    Each turn's speaker is 'user' (the owner typed it), 'agent' (anything else in
    the user role) or 'assistant', and the conversation's kind is 'owner' or
    'agent' (no owner turn). Returns None if the conversation is too short.
    """
    records = read_records(jsonl_path)
    if not records:
        return None

    # In a session an agent ran, nothing in the user role is the owner's.
    agent_session = any(is_agent_record(r) for r in records)

    # Extract metadata from first content record
    session_id = None
    workspace = None
    first_timestamp = None
    last_timestamp = None

    # Build turns by collapsing streaming chunks
    turns = []
    current_speaker = None
    current_parts = []
    current_timestamp = None
    current_has_tool = False

    for record in records:
        rec_type = record.get("type", "")

        if rec_type in _SKIP_TYPES:
            continue

        # Extract session metadata
        if not session_id and record.get("sessionId"):
            session_id = record["sessionId"]
        if not workspace and record.get("cwd"):
            workspace = record["cwd"]

        timestamp = record.get("timestamp")
        if timestamp:
            if not first_timestamp:
                first_timestamp = timestamp
            last_timestamp = timestamp

        if rec_type == "system":
            # System messages (hooks, etc.) — skip for turns
            continue

        if rec_type not in _CONTENT_TYPES:
            continue

        message = record.get("message", {})
        role = message.get("role", rec_type)

        text = _extract_text_content(message)
        if not text:
            continue

        if role != "user":
            speaker = ASSISTANT
        elif agent_session or not is_owner_record(record, text):
            speaker = AGENT
        else:
            speaker = OWNER

        has_tool = "[Tool:" in text

        # Collapse consecutive messages from same speaker
        if speaker == current_speaker:
            current_parts.append(text)
            if has_tool:
                current_has_tool = True
            if timestamp:
                current_timestamp = timestamp
        else:
            # Flush previous turn
            if current_speaker and current_parts:
                combined = "\n".join(current_parts)
                if len(combined) > MAX_TURN_CONTENT:
                    combined = combined[:MAX_TURN_CONTENT] + "\n[...truncated]"
                turns.append(
                    {
                        "speaker": current_speaker,
                        "content": combined,
                        "timestamp": current_timestamp or "",
                        "has_code": _has_code_blocks(combined),
                        "has_tool_use": current_has_tool,
                    }
                )

            current_speaker = speaker
            current_parts = [text]
            current_timestamp = timestamp
            current_has_tool = has_tool

    # Flush last turn
    if current_speaker and current_parts:
        combined = "\n".join(current_parts)
        if len(combined) > MAX_TURN_CONTENT:
            combined = combined[:MAX_TURN_CONTENT] + "\n[...truncated]"
        turns.append(
            {
                "speaker": current_speaker,
                "content": combined,
                "timestamp": current_timestamp or "",
                "has_code": _has_code_blocks(combined),
                "has_tool_use": current_has_tool,
            }
        )

    # Filter: need minimum turns from the user role, the owner's or not, as the
    # floor counted them before the owner's were told apart
    if sum(1 for t in turns if t["speaker"] != ASSISTANT) < MIN_USER_TURNS:
        return None

    # Use file UUID as fallback session_id
    if not session_id:
        session_id = jsonl_path.stem

    return {
        "session_id": session_id,
        "file_name": jsonl_path.name,
        "workspace": workspace or "",
        "project_name": _project_name_from_workspace(workspace or ""),
        "started_at": first_timestamp or "",
        "ended_at": last_timestamp or "",
        "turn_count": len(turns),
        "turns": turns,
        "kind": "owner" if any(t["speaker"] == OWNER for t in turns) else "agent",
    }


def scan_conversation_files(
    days: int | None = None,
    workspace_filter: str | None = None,
) -> list[Path]:
    """Find all conversation JSONL files, optionally filtered.

    Args:
        days: Only include conversations modified in the last N days
        workspace_filter: Only include conversations from this workspace substring
    """
    if not CLAUDE_CODE_PROJECTS_DIR.exists():
        return []

    files = []
    cutoff = None
    if days is not None:
        cutoff = datetime.now().timestamp() - (days * 86400)

    for project_dir in CLAUDE_CODE_PROJECTS_DIR.iterdir():
        if not project_dir.is_dir():
            continue

        # Apply workspace filter
        if workspace_filter:
            readable = _workspace_from_dir_name(project_dir.name)
            if workspace_filter.lower() not in readable.lower():
                continue

        for jsonl_file in project_dir.glob("*.jsonl"):
            if cutoff and jsonl_file.stat().st_mtime < cutoff:
                continue
            files.append(jsonl_file)

    # Sort by modification time (newest first for priority processing)
    files.sort(key=lambda f: f.stat().st_mtime, reverse=True)
    return files


def staged_path(staging_dir: Path, conv: dict) -> Path:
    """The file a copy of `conv` is staged in: one per session and version (its end and its
    turn count), so the same version exported again replaces its own file and a newer one
    goes beside it. A session id is a UUID; one holding anything else, or a long one, gets a
    digest of itself in the name, so that two ids never share a file."""
    session_id = str(conv.get("session_id") or "")
    key = re.sub(r"[^A-Za-z0-9_-]", "_", session_id)
    if key != session_id or not key or len(key) > 64:
        key = f"{key[:64]}_{hashlib.sha256(session_id.encode('utf-8')).hexdigest()[:12]}"
    ended = re.sub(r"\D", "", str(conv.get("ended_at") or ""))[:20].ljust(20, "0")
    turns = int(conv.get("turn_count") or len(conv.get("turns") or []))
    return Path(staging_dir) / f"conversation-session-{key}.{ended}.{turns:06d}.json"


def staged_files(staging_dir: Path) -> list[Path]:
    """Every staged file, in the order in which a later copy of a session wins."""
    return sorted(Path(staging_dir).glob(STAGED_GLOB))


def read_staged_conversations(staging_dir: Path):
    """(file, the conversations it holds) for every staged file. One a load removed since
    the listing is passed over; one that cannot be parsed is moved aside, as an unreadable
    mail batch is (load_json_or_quarantine)."""
    for path in staged_files(staging_dir):
        try:
            with open(path, encoding="utf-8") as f:
                data = json.load(f)
        except FileNotFoundError:
            continue
        except (json.JSONDecodeError, UnicodeDecodeError, OSError):
            data = load_json_or_quarantine(path)
            if data is None:
                continue
        yield path, data.get("conversations", []) if isinstance(data, dict) else []


def _code_version() -> str:
    """A digest of this module: what the export recorded of a transcript holds only for the
    code that read it."""
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()[:16]


def _transcripts_read(path: Path) -> dict[str, dict]:
    """The record export_conversations keeps, or nothing when it is missing, unreadable, or
    written by other code."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict) or data.get("code") != _code_version():
        return {}
    transcripts = data.get("transcripts")
    return transcripts if isinstance(transcripts, dict) else {}


def _held(conv: dict | None) -> dict | None:
    """What a transcript held, as the record keeps it: None when too short to export."""
    if conv is None:
        return None
    return {
        "session_id": conv["session_id"],
        "ended_at": conv["ended_at"],
        "turn_count": conv["turn_count"],
        "kind": conv.get("kind"),
    }


def _outcome_unread(
    held: dict | None,
    loaded: dict[str, tuple[str | None, int | None]],
    include_agents: bool,
    staging_dir: Path,
) -> str | None:
    """What an unchanged transcript comes to without reading it: 'skipped' (too short, or
    loaded and not gone on since), 'agents' (an agent session left out) or 'pending'
    (staged, its load to come). None when it has to be read: the store does not hold it
    and no copy of it is staged."""
    from src.store.loader import conversation_went_on

    if held is None:
        return "skipped"
    if held.get("kind") == "agent" and not include_agents:
        return "agents"
    previous = loaded.get(held.get("session_id") or "")
    if previous is not None and not conversation_went_on(held, *previous):
        return "skipped"
    if staged_path(staging_dir, held).is_file():
        return "pending"
    return None


def export_conversations(
    days: int | None = None,
    limit: int = 0,
    workspace_filter: str | None = None,
    loaded: dict[str, tuple[str | None, int | None]] | None = None,
    include_agents: bool = False,
) -> dict:
    """Export Claude Code conversations to staging directory.

    Each conversation goes to a file of its own (staged_path). Every transcript read is
    recorded with its size and mtime as they were before the read (TRANSCRIPTS_READ), and
    one that has not changed since is not read again: the 1.15 GB of the last week's
    transcripts were parsed on every export to skip the sessions already loaded. It is read
    again when the store no longer holds what it held and no copy is staged, and every one
    is read again after a change to this module.

    Args:
        days: Only export conversations from last N days (None = all)
        limit: Max conversations to export (0 = unlimited)
        workspace_filter: Only export from matching workspace
        loaded: session_id -> (ended_at, turn_count) of each conversation the
            store holds. One that has gone on since (conversation_went_on) is
            staged again, marked regrown_from with the end it was loaded at,
            so extraction takes it again; the rest are skipped.
        include_agents: Stage agent sessions too (kind 'agent': a teammate's,
            a subagent's, or one the owner typed nothing into), left out by default

    Returns:
        Dict with 'exported', 'skipped', 'agents' (agent sessions left out),
        'errors', 'pending' (staged before and not loaded yet, not read again) and
        'staged' (the files written) keys
    """
    CONVERSATION_STAGING_DIR.mkdir(parents=True, exist_ok=True)

    files = scan_conversation_files(days=days, workspace_filter=workspace_filter)
    if not files:
        return {
            "exported": 0,
            "skipped": 0,
            "agents": 0,
            "errors": 0,
            "pending": 0,
            "staged": [],
        }

    from src.store.loader import conversation_went_on

    loaded = loaded or {}
    record_path = CONVERSATION_STAGING_DIR / TRANSCRIPTS_READ
    known = _transcripts_read(record_path)
    record = {str(f): known[str(f)] for f in files if str(f) in known}
    conversations: list[dict] = []
    skipped = 0
    agents = 0
    errors = 0
    pending = 0

    for jsonl_file in files:
        if limit and len(conversations) >= limit:
            break

        try:
            st = jsonl_file.stat()
            seen: list[int] | None = [st.st_size, st.st_mtime_ns]
        except OSError:
            seen = None
        entry = known.get(str(jsonl_file))
        if seen is not None and entry is not None and entry.get("seen") == seen:
            outcome = _outcome_unread(
                entry.get("held"), loaded, include_agents, CONVERSATION_STAGING_DIR
            )
            if outcome == "skipped":
                skipped += 1
                continue
            if outcome == "agents":
                agents += 1
                continue
            if outcome == "pending":
                pending += 1
                continue

        try:
            conv = parse_conversation(jsonl_file)
        except Exception:
            errors += 1
            continue
        if seen is not None:
            record[str(jsonl_file)] = {"seen": seen, "held": _held(conv)}

        if conv is None:
            skipped += 1
            continue

        if conv.get("kind") == "agent" and not include_agents:
            agents += 1
            continue

        previous = loaded.get(conv["session_id"])
        if previous is not None:
            if not conversation_went_on(conv, *previous):
                skipped += 1
                continue
            conv["regrown_from"] = previous[0]

        conversations.append(conv)

    staged = []
    for conv in conversations:
        path = staged_path(CONVERSATION_STAGING_DIR, conv)
        write_json_atomic(path, {"conversations": [conv]}, redact=True)
        staged.append(str(path))
    write_json_atomic(record_path, {"code": _code_version(), "transcripts": record})

    return {
        "exported": len(conversations),
        "skipped": skipped,
        "agents": agents,
        "errors": errors,
        "pending": pending,
        "staged": staged,
    }
