"""Who said what in a Claude Code transcript comes from the record, not the role.

The exporter stored every user-role record as the owner's words. The user role
also carries skill and command bodies, compaction summaries, task notifications,
command output and the messages of other sessions and agents: 85% of the stored
user-turn text was not typed by the owner, and it fed the extracted preferences.
Claude Code marks most of it (isMeta, isCompactSummary, origin, promptSource);
the rest opens like the harness's own text. A session an agent ran, or one the
owner typed nothing into, is an agent session, left out unless asked for.

Every record here is synthetic.
"""

import json
from pathlib import Path

import pytest

from src.export import conversation_export as ce


def _user(text, ts="2026-10-01T10:00:00Z", **fields):
    return {
        "type": "user",
        "sessionId": "s1",
        "cwd": "/work/okapi",
        "timestamp": ts,
        "message": {"role": "user", "content": text},
        **fields,
    }


def _assistant(text, ts="2026-10-01T10:00:30Z", **fields):
    return {
        "type": "assistant",
        "sessionId": "s1",
        "cwd": "/work/okapi",
        "timestamp": ts,
        "message": {"role": "assistant", "content": [{"type": "text", "text": text}]},
        **fields,
    }


def _typed(text):
    return _user(text, origin={"kind": "human"}, promptSource="typed")


def _parse(tmp_path, *records, name="s1.jsonl"):
    path = tmp_path / name
    path.write_text("\n".join(json.dumps(r) for r in records) + "\n")
    return ce.parse_conversation(path)


def _speakers(conv):
    return [t["speaker"] for t in conv["turns"]]


def test_what_the_owner_typed_is_the_users(tmp_path):
    conv = _parse(
        tmp_path,
        _typed("rename the okapi table"),
        _assistant("done"),
        _user("and the index", origin={"kind": "human"}, promptSource="suggestion_accepted"),
        _assistant("done too"),
    )

    assert _speakers(conv) == ["user", "assistant", "user", "assistant"]
    assert conv["kind"] == "owner"


@pytest.mark.parametrize(
    "record",
    [
        _user("Base directory for this skill: /skills/okapi\n\nDo the thing.", isMeta=True),
        _user("This session is being continued from earlier.", isCompactSummary=True),
        _user(
            "<task-notification><summary>okapi done</summary></task-notification>",
            origin={"kind": "task-notification"},
            promptSource="system",
        ),
        _user("Report back on the okapi plan", origin={"kind": "peer"}, promptSource="system"),
        _user("Summarise the okapi plan", promptSource="sdk"),
        _user("Summarise the okapi plan", entrypoint="sdk-cli"),
        _user("Your usage limit has reset.", origin={"kind": "auto-continuation"}, isMeta=True),
    ],
    ids=["skill-body", "compaction", "task", "peer", "sdk", "sdk-entrypoint", "continuation"],
)
def test_what_claude_code_marks_as_its_own_is_not_the_owners(tmp_path, record):
    conv = _parse(tmp_path, _typed("look at the okapi plan"), _assistant("ok"), record)

    assert _speakers(conv) == ["user", "assistant", "agent"]


@pytest.mark.parametrize(
    "text",
    [
        "<teammate-message teammate_id='lead'>Report on the okapi plan</teammate-message>",
        "Another Claude session sent a message:\nCheck the okapi plan",
        "<command-message>okapi</command-message>\n<command-name>/okapi</command-name>",
        "<local-command-stdout>okapi ok</local-command-stdout>",
        "<local-command-caveat>Caveat: generated by local commands</local-command-caveat>",
        "<system-reminder>okapi context</system-reminder>",
        "<cross-session-message from='other'>okapi</cross-session-message>",
        "<bash-input>ls okapi</bash-input>",
        "[Request interrupted by user]",
        "Base directory for this skill: /skills/okapi",
        "This session is being continued from a previous conversation that ran out of context.",
    ],
)
def test_text_that_opens_like_the_harness_is_not_the_owners(tmp_path, text):
    """These carry none of the provenance fields, and nothing older than them does."""
    conv = _parse(tmp_path, _user("look at the okapi plan"), _assistant("ok"), _user(text))

    assert _speakers(conv) == ["user", "assistant", "agent"]


def test_a_transcript_from_before_the_fields_is_the_owners(tmp_path):
    conv = _parse(
        tmp_path,
        _user("look at the okapi plan"),
        _assistant("ok"),
        _user("now the budget"),
        _assistant("ok"),
    )

    assert _speakers(conv) == ["user", "assistant", "user", "assistant"]
    assert conv["kind"] == "owner"


def test_harness_text_after_the_owners_is_a_turn_of_its_own(tmp_path):
    """Collapsed by role, a skill body joined the owner's prompt and counted as typed."""
    conv = _parse(
        tmp_path,
        _typed("/okapi plan it"),
        _user("Base directory for this skill: /skills/okapi\n\nPlan it.", isMeta=True),
        _assistant("planned"),
        _typed("thanks"),
    )

    assert _speakers(conv) == ["user", "agent", "assistant", "user"]
    assert conv["turns"][0]["content"] == "/okapi plan it"


@pytest.mark.parametrize("field", ["agentName", "teamName", "agentId"])
def test_a_session_an_agent_ran_is_an_agent_session(tmp_path, field):
    """A teammate's or subagent's records name it. Even what looks typed there is
    an agent's conversation, never the owner's."""
    conv = _parse(
        tmp_path,
        _user("<teammate-message>plan the okapi</teammate-message>", **{field: "w1"}),
        _assistant("planning", **{field: "w1"}),
        _typed("and the budget") | {field: "w1"},
        _assistant("ok", **{field: "w1"}),
    )

    assert conv["kind"] == "agent"
    assert _speakers(conv) == ["agent", "assistant", "agent", "assistant"]


def test_a_session_title_does_not_make_an_agent_session(tmp_path):
    """Claude Code stores a session's name as a record of its own type, keyed agentName."""
    conv = _parse(
        tmp_path,
        {"type": "agent-name", "agentName": "Okapi planning", "sessionId": "s1"},
        _typed("look at the okapi plan"),
        _assistant("ok"),
        _typed("and the budget"),
    )

    assert conv["kind"] == "owner"


def test_a_session_the_owner_typed_nothing_into_is_an_agent_session(tmp_path):
    conv = _parse(
        tmp_path,
        _user("Summarise the okapi plan", promptSource="sdk"),
        _assistant("summary"),
        _user("<task-notification>done</task-notification>", origin={"kind": "task-notification"}),
        _assistant("noted"),
    )

    assert conv["kind"] == "agent"
    assert "user" not in _speakers(conv)


def test_a_single_exchange_is_still_too_short_to_export(tmp_path):
    assert _parse(tmp_path, _typed("hello"), _assistant("hi")) is None


