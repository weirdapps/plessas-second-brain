    """Two transcripts, one the owner's and one a teammate's, and the staging dir."""
    monkeypatch.setattr(ce, "CONVERSATION_STAGING_DIR", tmp_path / "staging")
    owner = [_typed("plan the okapi"), _assistant("ok"), _typed("and the budget")]
